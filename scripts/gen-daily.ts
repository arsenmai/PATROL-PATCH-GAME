/**
 * Generates src/sim/daily-data.ts: a rotation of seeded heists, each one validated by the exhaustive solver.
 *
 *   npx vite-node scripts/gen-daily.ts [count]
 *
 * A seed is kept only if the resulting heist is fair and interesting:
 *   - at least one artifact can be stolen on factory AI,
 *   - the right patch is worth something (it beats factory AI),
 *   - all three artifacts are possible with the best patch.
 * The turn limit is then set so the perfect heist finishes with SLACK turns to spare.
 */
import { writeFileSync } from 'node:fs';
import { CURSES } from '../src/sim/curses';
import { buildVariant, variantFromSeed, type DailyHeist } from '../src/sim/daily';
import { totalLoot } from '../src/sim/level';
import { allPatches } from '../src/sim/patch';
import { solve } from '../src/sim/solver';

const WANTED = Number(process.argv[2] ?? 14);
const SLACK = 7;
const OPEN_LIMIT = 200;
const out: DailyHeist[] = [];

for (let seed = 1; out.length < WANTED && seed < 400; seed++) {
  const variant = variantFromSeed(seed);
  const open = buildVariant(variant, OPEN_LIMIT);
  const everything = totalLoot(open);

  const stock = solve(open, null);
  if (stock.loot === 0 || stock.loot === everything) continue;

  let best = stock;
  for (const patch of allPatches(open)) {
    const s = solve(open, patch);
    if (s.loot > best.loot || (s.loot === best.loot && s.actions.length < best.actions.length)) best = s;
  }
  if (best.loot !== everything) continue;

  // The perfect heist always includes the Hourglass, which costs turns on top of the ones actually played.
  const turnLimit = best.actions.length + (CURSES.HOURGLASS.turnPenalty ?? 0) + SLACK;
  const timed = buildVariant(variant, turnLimit);
  const withoutPatch = solve(timed, null).loot;
  if (withoutPatch === 0) continue;

  out.push({ seed, variant, turnLimit, par: { withoutPatch, withBestPatch: best.loot, bestTurns: best.actions.length } });
  console.log(`seed ${seed}: sealed=${variant.sealed} par ${withoutPatch}/${best.loot} in ${best.actions.length} turns, limit ${turnLimit}`);
}

const body = out.map((h) => `  ${JSON.stringify(h)},`).join('\n');
writeFileSync(
  'src/sim/daily-data.ts',
  `// GENERATED by scripts/gen-daily.ts — do not edit by hand.\nimport type { DailyHeist } from './daily';\n\nexport const DAILY_HEISTS: readonly DailyHeist[] = [\n${body}\n];\n`,
);
console.log(`wrote ${out.length} heists`);
